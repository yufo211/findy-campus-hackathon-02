/**
 * 固定のお題リスト。
 * 将来ユーザーが出題できるようにするため、お題は「ルーム生成時に外から注入する値」
 * として扱う（RoomAgent は topic を受け取るだけで、出どころを知らない）。
 */
export const TOPICS = [
  'こんな寿司屋は嫌だ。どんな寿司屋？',
  '宇宙人が地球を侵略しなかった理由とは？',
  '売れなかった自動販売機。何を売っていた？',
  '猫が人間に一言モノ申すとしたら？',
  '史上最悪の目覚まし時計の起こし方とは？',
  'ドラゴンが引退後に始めた仕事は？',
  'この世で一番いらない資格とは？',
  '「絶対に押すなよ」と言われたボタンの正体は？',
  'コンビニ店員が心の中で叫んでいることは？',
  '未来の小学校で廃止された教科は？',
  '魔法使いが最後に使った、しょうもない魔法とは？',
  'ヒーローが変身に失敗した理由とは？',
  '10000手先が読めるようになった藤井聡太が最近悩んでいること'
] as const

export function pickTopic(exclude?: string): string {
  const pool = TOPICS.filter((t) => t !== exclude)
  return pool[Math.floor(Math.random() * pool.length)]
}
